
import streamlit as st
import pandas as pd
import numpy as np
import joblib
import os

# Load trained model
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
MODEL_PATH = os.path.join(
    BASE_DIR, "diabetes_model.pkl"
)

bundle = joblib.load(MODEL_PATH)
model = bundle["model"]
features = bundle["features"]

# Page configuration
st.set_page_config(
    page_title="Diabetes Prediction",
    page_icon="🩺",
    layout="centered"
)

st.title("🩺 Diabetes Prediction System")
st.write(
    "Enter the health parameters below "
    "to get an ML model prediction."
)

st.info("This application is an educational project, not a medical diagnosis.")

with st.form("prediction_form"):

    st.subheader("Enter Patient Details")

    pregnancies = st.number_input(
        "Pregnancies", min_value=0, max_value=20, value=1
    )

    glucose = st.number_input(
        "Glucose Level", min_value=0.0, value=120.0
    )

    bp = st.number_input(
        "Blood Pressure", min_value=0.0, value=70.0
    )

    skin = st.number_input(
        "Skin Thickness", min_value=0.0, value=20.0
    )

    insulin = st.number_input(
        "Insulin", min_value=0.0, value=80.0
    )

    bmi = st.number_input(
        "BMI", min_value=0.0, value=25.0
    )

    dpf = st.number_input(
        "Diabetes Pedigree Function",
        min_value=0.0, value=0.5
    )

    age = st.number_input(
        "Age", min_value=1, max_value=120, value=30
    )

    submit = st.form_submit_button(
        "Predict Diabetes"
    )

if submit:

    input_data = pd.DataFrame([{
        "Pregnancies": pregnancies,
        "Glucose": glucose,
        "BloodPressure": bp,
        "SkinThickness": skin,
        "Insulin": insulin,
        "BMI": bmi,
        "DiabetesPedigreeFunction": dpf,
        "Age": age
    }])

    # Apply the same zero-as-missing
    # preprocessing used during training.
    for col in [
        "Glucose",
        "BloodPressure",
        "SkinThickness",
        "Insulin",
        "BMI"
    ]:
        if input_data.loc[0, col] == 0:
            input_data.loc[0, col] = np.nan

    input_data = input_data[features]

    prediction = model.predict(input_data)[0]

    probability = model.predict_proba(
        input_data
    )[0][1]

    st.subheader("Prediction Result")

    st.metric(
        "Model-estimated probability",
        f"{probability * 100:.2f}%"
    )

    if prediction == 1:
        st.error(
            "Model Prediction: Diabetes (Positive)"
        )
    else:
        st.success(
            "Model Prediction: No Diabetes (Negative)"
        )

    st.caption(
        "This result is generated by a machine learning "
        "model and must not be used for medical decisions."
    )
